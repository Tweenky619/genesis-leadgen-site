#!/usr/bin/env python3
"""Regenerate the dark-mode stylesheet in public/index.html.

Reads the app's main <style> block, flips the lightness of every hex color
(keeping hue), and writes the result between the DARK-THEME markers.
Run after changing colors in the main stylesheet:  python3 tools/gen-dark.py
"""
import re, colorsys, pathlib

P = pathlib.Path(__file__).resolve().parent.parent / "public" / "index.html"
START, END = "/* DARK-THEME:START (generated by tools/gen-dark.py, do not edit) */", "/* DARK-THEME:END */"

def flip(hexc):
    h = hexc.lstrip("#")
    if len(h) == 3: h = "".join(c * 2 for c in h)
    if len(h) != 6: return hexc
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    hh, l, s = colorsys.rgb_to_hls(r, g, b)
    if s > 0.35 and 0.3 <= l <= 0.65:          # strong mid colors (buttons, accents): keep, lift a little
        l2 = min(0.72, l + 0.12)
    else:
        l2 = 0.09 + (1 - l) * 0.84               # light -> dark surface, dark -> light text
        if l > 0.85: s = s * 0.55                 # pale tints become muted dark tints
    r2, g2, b2 = colorsys.hls_to_rgb(hh, l2, s)
    return "#%02x%02x%02x" % (round(r2 * 255), round(g2 * 255), round(b2 * 255))

HEX = re.compile(r"#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b")

def prefix(sel):
    out = []
    for s in sel.split(","):
        s = s.strip()
        if not s or s.startswith(":root"): continue
        if s.startswith("html"): out.append("html.dark" + s[4:])
        elif s.startswith(".wl-app") or s.startswith(".wl-no-"): out.append("html.dark" + s)   # these classes sit on <html>
        else: out.append("html.dark " + s)
    return ",".join(out)

def rules(css):
    out, i, n = [], 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j < 0: break
        head = css[i:j].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            if css[k] == "{": depth += 1
            elif css[k] == "}": depth -= 1
            k += 1
        body = css[j + 1:k - 1]
        if head.startswith("@media") or head.startswith("@supports"):
            inner = rules(body)
            if inner: out.append(head + "{" + "".join(inner) + "}")
        elif head.startswith("@"):
            pass
        else:
            decls = [d.strip() for d in body.split(";") if HEX.search(d) and ":" in d and "--" not in d.split(":")[0]]
            sel = prefix(head)
            if decls and sel:
                out.append(sel + "{" + ";".join(HEX.sub(lambda m: flip(m.group(0)), d) for d in decls) + "}")
        i = k
    return out

src = P.read_text()
m = re.search(r"<style>(.*?)</style>", src, re.S)
main = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
gen = "\n".join(rules(main))
block = START + "\n" + gen + "\n" + END
if START in src:
    src = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, src, flags=re.S)
else:
    raise SystemExit("markers not found: add an empty DARK-THEME block first")
P.write_text(src)
print("dark rules:", gen.count("{"))

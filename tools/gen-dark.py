#!/usr/bin/env python3
"""Regenerate the dark-mode stylesheet in public/index.html.

Reads the app's main <style> block, flips the lightness of every hex color
(keeping hue), and writes the result between the DARK-THEME markers.
Run after changing colors in the main stylesheet:  python3 tools/gen-dark.py
"""
import re, colorsys, pathlib

P = pathlib.Path(__file__).resolve().parent.parent / "public" / "index.html"
START, END = "/* DARK-THEME:START (generated by tools/gen-dark.py, do not edit) */", "/* DARK-THEME:END */"

def flip(hexc, tint=None):
    h = hexc.lstrip("#")
    if len(h) == 3: h = "".join(c * 2 for c in h)
    if len(h) != 6: return hexc
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    hh, l, s = colorsys.rgb_to_hls(r, g, b)
    if s > 0.35 and 0.3 <= l <= 0.65:          # strong mid colors (buttons, accents): keep, lift a little
        l2 = min(0.72, l + 0.12)
    else:
        l2 = 0.09 + (1 - l) * 0.84               # light -> dark surface, dark -> light text
        if l > 0.85: s = s * 0.55                 # pale tints become muted dark tints
    if tint is not None and s < 0.2 and l2 < 0.4:    # dark neutral surfaces take the tint hue (e.g. burgundy)
        hh, s = tint, 0.42
    r2, g2, b2 = colorsys.hls_to_rgb(hh, l2, s)
    return "#%02x%02x%02x" % (round(r2 * 255), round(g2 * 255), round(b2 * 255))

HEX = re.compile(r"#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b")

def prefix(sel):
    out = []
    for s in sel.split(","):
        s = s.strip()
        if not s or s.startswith(":root"): continue
        if s.startswith("html"): out.append("html.dark" + s[4:])
        elif s.startswith(".wl-app") or s.startswith(".wl-no-"): out.append("html.dark" + s)   # these classes sit on <html>
        else: out.append("html.dark " + s)
    return ",".join(out)

def prefix_mine(sel):
    out = []
    for s in sel.split(","):
        s = s.strip()
        if not s or s.startswith(":root") or ":not(.wl-app)" in s: continue
        if s.startswith("html"): out.append("html.dark.lg-mine" + s[4:])
        elif s.startswith(".wl-app") or s.startswith(".wl-no-"): out.append("html.dark.lg-mine" + s)
        else: out.append("html.dark.lg-mine " + s)
    return ",".join(out)

TINT = None   # set to a hue (0-1) for the tinted pass
def rules(css):
    out, i, n = [], 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j < 0: break
        head = css[i:j].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            if css[k] == "{": depth += 1
            elif css[k] == "}": depth -= 1
            k += 1
        body = css[j + 1:k - 1]
        if head.startswith("@media") or head.startswith("@supports"):
            inner = rules(body)
            if inner: out.append(head + "{" + "".join(inner) + "}")
        elif head.startswith("@"):
            pass
        else:
            decls = [d.strip() for d in body.split(";") if HEX.search(d) and ":" in d and "--" not in d.split(":")[0]]
            if TINT is None:
                sel = prefix(head)
                if decls and sel:
                    out.append(sel + "{" + ";".join(HEX.sub(lambda m: flip(m.group(0)), d) for d in decls) + "}")
            else:   # only declarations whose dark color changes with the tint
                sel = prefix_mine(head)
                keep = [HEX.sub(lambda m: flip(m.group(0), TINT), d) for d in decls if HEX.sub(lambda m: flip(m.group(0), TINT), d) != HEX.sub(lambda m: flip(m.group(0)), d)]
                if keep and sel:
                    out.append(sel + "{" + ";".join(keep) + "}")
        i = k
    return out

src = P.read_text()
m = re.search(r"<style>(.*?)</style>", src, re.S)
main = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
gen = "\n".join(rules(main))
# Home Connector light mode: white surfaces become platinum
def plat(css):
    out, i, n = [], 0, len(css)
    WHITE = re.compile(r"^(background(?:-color)?)\s*:\s*(#fff|#ffffff|white)\b(.*)$", re.I)
    while i < n:
        j = css.find("{", i)
        if j < 0: break
        head = css[i:j].strip(); depth, k = 1, j + 1
        while k < n and depth:
            if css[k] == "{": depth += 1
            elif css[k] == "}": depth -= 1
            k += 1
        body = css[j + 1:k - 1]
        if head.startswith("@media") or head.startswith("@supports"):
            inner = plat(body)
            if inner: out.append(head + "{" + "".join(inner) + "}")
        elif not head.startswith("@"):
            keep = []
            for d in body.split(";"):
                m = WHITE.match(d.strip())
                if m: keep.append(m.group(1) + ":#e5e4e2" + m.group(3))
            sels = []
            for s in head.split(","):
                s = s.strip()
                if not s or s.startswith(":root") or ":not(.wl-app)" in s: continue
                if s.startswith("html"): sels.append("html.lg-mine:not(.dark)" + s[4:])
                elif s.startswith(".wl-app") or s.startswith(".wl-no-"): sels.append("html.lg-mine:not(.dark)" + s)
                else: sels.append("html.lg-mine:not(.dark) " + s)
            if keep and sels: out.append(",".join(sels) + "{" + ";".join(keep) + "}")
        i = k
    return out
platinum = "\n".join(plat(main))
TINT = 345 / 360   # Home Connector: burgundy dark mode
gen += "\n/* Home Connector burgundy */\n" + "\n".join(rules(main))
gen += "\n/* Home Connector light: platinum surfaces */\n" + platinum
block = START + "\n" + gen + "\n" + END
if START in src:
    src = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, src, flags=re.S)
else:
    raise SystemExit("markers not found: add an empty DARK-THEME block first")
P.write_text(src)
print("dark rules:", gen.count("{"))
